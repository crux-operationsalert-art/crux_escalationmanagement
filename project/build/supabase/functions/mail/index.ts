// =====================================================================
// Crux — the sender.
//
// The outbox has held messages since the base schema and has never had a
// way out of the building. This is it. It claims a batch, hands each
// message to whichever transport is configured, and records the outcome
// on the row — sent with the provider's own reference, or deferred with
// the provider's own error text, so a failure is diagnosable a week later
// without anybody having been watching at the time.
//
// Two kinds of transport, because the person who administers this tool
// does not administer the Google Workspace it sits in:
//
//   * an HTTPS transactional provider (resend, sendgrid, brevo,
//     postmark) — a domain and DNS, no Workspace console;
//   * gmail_oauth — the Gmail API on one mailbox, through an OAuth client
//     the tool admin already owns.
//
// There is no SMTP path and there will not be one: an edge function may
// make an HTTPS request and nothing else, so a Gmail app password has
// nowhere to go from here.
//
// Nothing in this file holds a secret. Every key comes from mail_settings()
// at the moment of sending and is gone when the request ends.
//
// The gateway's JWT check is off; this function does its own, and the only
// caller it accepts is one holding the service-role key — pg_cron, through
// pg_net, every minute.
// =====================================================================
const SUPABASE_URL = Deno.env.get("SUPABASE_URL")!;
const SERVICE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;

async function rpc(fn: string, args: Record<string, unknown> = {}) {
  const r = await fetch(SUPABASE_URL + "/rest/v1/rpc/" + fn, {
    method: "POST",
    headers: {
      apikey: SERVICE_KEY,
      authorization: "Bearer " + SERVICE_KEY,
      "content-type": "application/json",
    },
    body: JSON.stringify(args),
  });
  const text = await r.text();
  if (!r.ok) throw new Error(fn + ": " + r.status + " " + text);
  return text ? JSON.parse(text) : null;
}

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json" },
  });

// A provider's failure text is written to a row an administrator reads.
// Trim it: some of them return a whole HTML page.
const trim = (s: string) => (s || "").replace(/\s+/g, " ").trim().slice(0, 500);

type Msg = {
  id: string; template_key: string; recipient: string;
  cc_addr: string | null; subject: string; body: string;
  entity_type: string | null; entity_id: string | null; attempts: number;
};
type Cfg = Record<string, string>;

// ------------------------------------------------------------ the body
// Every message is plain text with an HTML twin. The twin exists because
// a plain-text-only message from an unknown domain scores badly with
// filters, and an escalation that lands in spam is an escalation that did
// not happen.
const esc = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function html(m: Msg) {
  const paras = m.body.split(/\n{2,}/).map((p) =>
    `<p style="margin:0 0 14px;line-height:1.55">${esc(p).replace(/\n/g, "<br>")}</p>`
  ).join("");
  return `<div style="font:15px/1.55 -apple-system,Segoe UI,Roboto,sans-serif;color:#1a1a1a;max-width:640px">
${paras}
<hr style="border:0;border-top:1px solid #e3e3e3;margin:22px 0 12px">
<p style="margin:0;font-size:12px;color:#767676">Sent by Crux. This message was generated by the escalation and assignment workflow; replies reach the address above.</p>
</div>`;
}

// ---------------------------------------------------------- transports
// Each returns a provider reference on success and throws on failure. The
// reference goes on the delivery row, so "did it send?" is answerable
// against the provider's own records rather than against our belief.

async function post(url: string, headers: Record<string, string>, body: unknown) {
  const r = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json", ...headers },
    body: JSON.stringify(body),
  });
  const text = await r.text();
  if (!r.ok) throw new Error(r.status + " " + trim(text));
  try { return JSON.parse(text); } catch { return { raw: text }; }
}

const fromLine = (c: Cfg) =>
  c.mail_from_name ? `${c.mail_from_name} <${c.mail_from}>` : c.mail_from;

async function sendResend(c: Cfg, m: Msg) {
  const r = await post("https://api.resend.com/emails",
    { authorization: "Bearer " + c.mail_api_key }, {
      from: fromLine(c), to: [m.recipient],
      ...(m.cc_addr ? { cc: m.cc_addr.split(/[,;]/).map((s) => s.trim()) } : {}),
      ...(c.mail_reply_to ? { reply_to: c.mail_reply_to } : {}),
      subject: m.subject, text: m.body, html: html(m),
    });
  return r?.id ?? null;
}

async function sendSendgrid(c: Cfg, m: Msg) {
  // SendGrid answers 202 with an empty body; its reference is in a header,
  // so this one is fetched by hand rather than through post().
  const r = await fetch("https://api.sendgrid.com/v3/mail/send", {
    method: "POST",
    headers: {
      authorization: "Bearer " + c.mail_api_key,
      "content-type": "application/json",
    },
    body: JSON.stringify({
      personalizations: [{
        to: [{ email: m.recipient }],
        ...(m.cc_addr
          ? { cc: m.cc_addr.split(/[,;]/).map((s) => ({ email: s.trim() })) }
          : {}),
      }],
      from: { email: c.mail_from, name: c.mail_from_name || undefined },
      ...(c.mail_reply_to ? { reply_to: { email: c.mail_reply_to } } : {}),
      subject: m.subject,
      content: [{ type: "text/plain", value: m.body },
                { type: "text/html", value: html(m) }],
    }),
  });
  if (!r.ok) throw new Error(r.status + " " + trim(await r.text()));
  return r.headers.get("x-message-id");
}

async function sendBrevo(c: Cfg, m: Msg) {
  const r = await post("https://api.brevo.com/v3/smtp/email",
    { "api-key": c.mail_api_key }, {
      sender: { email: c.mail_from, name: c.mail_from_name || undefined },
      to: [{ email: m.recipient }],
      ...(m.cc_addr
        ? { cc: m.cc_addr.split(/[,;]/).map((s) => ({ email: s.trim() })) }
        : {}),
      ...(c.mail_reply_to ? { replyTo: { email: c.mail_reply_to } } : {}),
      subject: m.subject, textContent: m.body, htmlContent: html(m),
    });
  return r?.messageId ?? null;
}

async function sendPostmark(c: Cfg, m: Msg) {
  const r = await post("https://api.postmarkapp.com/email",
    { "X-Postmark-Server-Token": c.mail_api_key, accept: "application/json" }, {
      From: fromLine(c), To: m.recipient,
      ...(m.cc_addr ? { Cc: m.cc_addr } : {}),
      ...(c.mail_reply_to ? { ReplyTo: c.mail_reply_to } : {}),
      Subject: m.subject, TextBody: m.body, HtmlBody: html(m),
      MessageStream: "outbound",
    });
  return r?.MessageID ?? null;
}

// ------------------------------------------------------------ Gmail API
// One access token per drain, not per message: the refresh grant is
// rate-limited and a batch of forty escalations would otherwise ask for
// forty tokens.
async function gmailToken(c: Cfg) {
  const body = new URLSearchParams({
    client_id: c.mail_oauth_client_id || c.google_client_id,
    client_secret: c.mail_oauth_client_secret,
    refresh_token: c.mail_oauth_refresh_token,
    grant_type: "refresh_token",
  });
  const r = await fetch("https://oauth2.googleapis.com/token", {
    method: "POST",
    headers: { "content-type": "application/x-www-form-urlencoded" },
    body,
  });
  const text = await r.text();
  if (!r.ok) {
    // invalid_grant means the mailbox withdrew consent or the token expired
    // after six months of disuse. Say which, because the remedies differ.
    throw new Error(
      trim(text).includes("invalid_grant")
        ? "The Gmail grant is no longer valid. Consent again on the Mail screen."
        : "token: " + r.status + " " + trim(text),
    );
  }
  return JSON.parse(text).access_token as string;
}

// RFC 2822, base64url. Non-ASCII in a header has to be encoded-word or it
// is silently mangled; subjects here carry client names and Indian place
// names, so this is not hypothetical.
function mime(c: Cfg, m: Msg) {
  const b64 = (s: string) =>
    btoa(String.fromCharCode(...new TextEncoder().encode(s)));
  const hdr = (s: string) => /[^\x20-\x7e]/.test(s) ? `=?UTF-8?B?${b64(s)}?=` : s;
  const bound = "crux" + Math.random().toString(36).slice(2);
  const lines = [
    `From: ${c.mail_from_name ? `${hdr(c.mail_from_name)} <${c.mail_from}>` : c.mail_from}`,
    `To: ${m.recipient}`,
    ...(m.cc_addr ? [`Cc: ${m.cc_addr}`] : []),
    ...(c.mail_reply_to ? [`Reply-To: ${c.mail_reply_to}`] : []),
    `Subject: ${hdr(m.subject)}`,
    "MIME-Version: 1.0",
    `Content-Type: multipart/alternative; boundary="${bound}"`,
    "",
    `--${bound}`,
    'Content-Type: text/plain; charset="UTF-8"',
    "Content-Transfer-Encoding: base64",
    "",
    b64(m.body),
    `--${bound}`,
    'Content-Type: text/html; charset="UTF-8"',
    "Content-Transfer-Encoding: base64",
    "",
    b64(html(m)),
    `--${bound}--`,
    "",
  ];
  return b64(lines.join("\r\n"))
    .replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

async function sendGmail(c: Cfg, m: Msg, token: string) {
  const r = await post(
    "https://gmail.googleapis.com/gmail/v1/users/me/messages/send",
    { authorization: "Bearer " + token }, { raw: mime(c, m) });
  return r?.id ?? null;
}

// ---------------------------------------------------------------- drain
async function drain(limit: number) {
  const cfg: Cfg = (await rpc("mail_settings")) ?? {};
  const provider = (cfg.mail_provider || "").trim();

  // Nothing configured is not a failure. The queue waits, intact, and says
  // so — a message deferred because there is no transport must not burn an
  // attempt and reach ABANDONED before anyone has set one up.
  if (!provider) {
    const st = await rpc("mail_status");
    return {
      held: "no_transport_configured",
      reason: "No mail provider is set. Nothing was claimed; the queue is intact.",
      queued: st?.queued ?? 0,
    };
  }
  if (provider !== "gmail_oauth" && !cfg.mail_api_key) {
    return { held: "no_key", reason: `${provider} is selected but no API key is set.` };
  }
  if (provider === "gmail_oauth" && !cfg.mail_oauth_refresh_token) {
    return { held: "no_grant", reason: "Gmail is selected but the mailbox has not consented yet." };
  }
  if (!cfg.mail_from) {
    return { held: "no_from", reason: "No from address is set." };
  }

  // Anything deferred whose wait is up rejoins the queue before we claim.
  await rpc("outbox_requeue");

  const claim = await rpc("outbox_claim", { p_limit: limit });
  if (claim?.held) return claim;
  const msgs: Msg[] = claim?.messages ?? [];
  if (msgs.length === 0) return { sent: 0, failed: 0, note: "Nothing waiting." };

  let token = "";
  if (provider === "gmail_oauth") {
    try {
      token = await gmailToken(cfg);
    } catch (e) {
      // The token failed, not the messages. Defer every claimed row with
      // the same reason rather than letting each one discover it.
      for (const m of msgs) {
        await rpc("outbox_failed", { p_id: m.id, p_error: String((e as Error).message) });
      }
      return { sent: 0, failed: msgs.length, error: String((e as Error).message) };
    }
  }

  let sent = 0, failed = 0;
  const errors: string[] = [];
  for (const m of msgs) {
    try {
      let ref: string | null = null;
      if (provider === "resend") ref = await sendResend(cfg, m);
      else if (provider === "sendgrid") ref = await sendSendgrid(cfg, m);
      else if (provider === "brevo") ref = await sendBrevo(cfg, m);
      else if (provider === "postmark") ref = await sendPostmark(cfg, m);
      else if (provider === "gmail_oauth") ref = await sendGmail(cfg, m, token);
      else throw new Error("unknown provider " + provider);

      await rpc("outbox_sent", { p_id: m.id, p_ref: ref });
      sent++;
    } catch (e) {
      const msg = trim(String((e as Error).message));
      await rpc("outbox_failed", { p_id: m.id, p_error: msg });
      errors.push(m.recipient + ": " + msg);
      failed++;
    }
  }
  return { provider, sent, failed, ...(errors.length ? { errors: errors.slice(0, 5) } : {}) };
}

// ------------------------------------------------------------------ door
// Two callers are accepted and no others. The scheduler presents a shared
// secret that lives in app_setting and was generated in the database, so
// nobody has ever typed it; an operator driving a drain by hand presents
// the service-role key. Both comparisons are length-independent, because
// this is a public URL.
const same = (a: string, b: string) => a.length === b.length && a === b;

Deno.serve(async (req) => {
  const auth = (req.headers.get("authorization") || "").replace(/^Bearer\s+/i, "");
  const cron = req.headers.get("x-crux-cron") || "";

  let allowed = same(auth, SERVICE_KEY);
  if (!allowed && cron) {
    try {
      allowed = same(cron, String(await rpc("mail_cron_secret")));
    } catch { allowed = false; }
  }
  if (!allowed) return json({ error: "unauthorised" }, 401);

  const url = new URL(req.url);
  const path = url.pathname.replace(/^\/mail/, "") || "/";

  try {
    if (path === "/status") return json(await rpc("mail_status"));
    const limit = Math.min(Number(url.searchParams.get("limit") || 50) || 50, 200);
    return json(await drain(limit));
  } catch (e) {
    return json({ error: "sender_failed", reason: String((e as Error).message) }, 500);
  }
});
